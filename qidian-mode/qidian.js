  const QUOTE_PAIRS = [['"', '"'], ["“", "”"], ["「", "」"], ["『", "』"]];

  function dialogueRatio(text) {
    let inside = 0;
    for (const [open, close] of QUOTE_PAIRS) {
      const re = open === close
        ? new RegExp(open + "([^" + open + "]{1,400})" + close, "g")
        : new RegExp(open + "([^" + close + "]{1,400})" + close, "g");
      let m;
      while ((m = re.exec(text))) inside += m[1].length;
    }
    return text.length ? inside / text.length : 0;
  }

